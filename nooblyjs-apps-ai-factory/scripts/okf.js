// npm run docs:okf            makes every NooblyJS document follow the Open Knowledge Format (OKF) v0.2
// npm run docs:okf -- --check changes nothing; exits 1 if a document or an index does not conform
//
// OKF (https://github.com/GoogleCloudPlatform/open-knowledge-format, SPEC.md v0.2): a knowledge bundle is a folder of
// Markdown files. Each document starts with YAML frontmatter whose `type` is required; `title`, `description` and
// `tags` are recommended. `index.md` and `log.md` are reserved names. The bundle-root `index.md` lists the documents
// and declares `okf_version`, and is the only index that may have frontmatter.
//
// The bundles are the documentation folders: the solution root's `.claude/`, each app's `.claude/` (src/apps/<app>/),
// each `docs/`, Knowledge's `.docs/`, and the `.claude/` of the harness and the desktop app, which sit beside the
// solution in nooblyjs-apps. The root's and each app's README.md, CLAUDE.md and SECURITY.md are documents too.
// Data and seed Markdown under `data/` and `src/`, test fixtures and examples are content the code reads, not
// documentation, and are left alone.
//
// What this adds: the missing frontmatter keys only (type, title, description, tags), derived from the path, the first
// heading and the first paragraph. It never overwrites a key that is there, never touches a document's body, and
// leaves the steering copies to `npm run steering:sync` (they are byte copies of the shared rules).
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { steeringCopies } from './sync-steering.js';

export const OKF_VERSION = '0.2';
// The solution root: the host at the top, its apps under src/apps/.
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APPS = path.join('src', 'apps');
const BUNDLE_DIRS = ['.claude', 'docs', '.docs'];
const ROOT_DOCS = ['README.md', 'CLAUDE.md', 'SECURITY.md'];
// Projects beside the solution, in nooblyjs-apps (paths relative to the solution root). Their bundles are indexed
// here too, under their own project names.
const EXTERNAL = [
  { dir: '../nooblyjs-apps-ai-harness', project: 'nooblyjs-ai-harness' },
  { dir: '../nooblyjs-apps-ai-desktop', project: 'nooblyjs-ai-desktop' },
];
const SKIP = new Set(['node_modules', '.git']);
const RESERVED = new Set(['index.md', 'log.md']);
const GENERATED_NOTE = '<!-- Generated by `npm run docs:okf` (OKF v0.2 index). Do not edit by hand. -->';

/**
 * A document's path as [project, ...rest]: an app's document (src/apps/<app>/…) starts with nooblyjs-ai-<app>, and the
 * leading ../ of a project beside the solution is dropped. Types and tags read the path this way.
 */
export function segments(rel) {
  const p = rel.split('/').filter((s) => s !== '..');
  if (p[0] === 'src' && p[1] === 'apps' && p.length > 3) return [`nooblyjs-ai-${p[2]}`, ...p.slice(3)];
  return p;
}

/** The OKF `type` of a document, from where it lives. Types are free strings in OKF; these are NooblyJS's. */
export function typeFor(rel) {
  const p = segments(rel);
  const name = p.at(-1);
  if (name === 'README.md' && p.length <= 2) return 'Readme';
  if (name === 'CLAUDE.md') return 'Agent Instructions';
  if (name === 'SECURITY.md') return 'Policy';
  if (p.includes('skills')) return name === 'SKILL.md' ? 'Skill' : 'Reference';
  if (p.includes('commands')) return 'Command';
  if (p.includes('agents')) return 'Agent Definition';
  if (p.includes('steering')) return /roadmap/i.test(name) ? 'Roadmap' : 'Steering';
  if (p.includes('specs')) {
    if (/roadmap/i.test(name)) return 'Roadmap';
    if (name === 'requirements.md') return 'Requirements';
    if (name === 'design.md') return 'Design';
    if (name === 'tasks.md') return 'Task List';
    return 'Specification';
  }
  if (p.includes('phases')) return 'Phase Summary';
  if (p.includes('adr')) return 'Architecture Decision Record';
  if (p.includes('guides')) return 'Guide';
  if (p.includes('runbooks')) return 'Runbook';
  if (p.includes('audits')) return 'Audit';
  if (p.includes('learning')) return 'Tutorial';
  return 'Reference';
}

const plain = (text) => text
  .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
  .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
  .replace(/[*_]{1,3}([^*_]+)[*_]{1,3}/g, '$1')
  .replace(/<[^>]+>/g, '')
  .replace(/\s+/g, ' ')
  .trim();

function firstSentence(text, max = 200) {
  const s = plain(text);
  const m = s.match(/^(.+?[.!?])(\s|$)/);
  const one = (m ? m[1] : s).trim();
  return one.length > max ? `${one.slice(0, max - 1).trimEnd()}…` : one;
}

/** Splits a document into its frontmatter (raw text and parsed) and body. */
export function splitDoc(text) {
  const src = text.replace(/^﻿/, '');
  const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---[ \t]*(\r?\n|$)/);
  if (!m) return { raw: null, data: null, body: src };
  let data = null;
  try { data = yaml.load(m[1]) ?? {}; } catch { data = null; }
  return { raw: m[1], data, body: src.slice(m[0].length) };
}

/**
 * Title and description from the body: the first heading, and the first paragraph after it (a quote counts, as many
 * documents open with a summary quote) unless that is a status line; otherwise the first paragraph of prose. A list
 * item's wrapped lines belong to the list, not to a paragraph.
 */
export function summarise(body, rel) {
  const lines = body.split(/\r?\n/);
  let title = null;
  const paras = [];
  let current = [];
  let quote = false;
  let fence = false;
  let inBlock = false; // inside a list or table: continuation lines are part of it
  const flush = () => { if (current.length) paras.push({ text: current.join(' '), quote }); current = []; };
  for (const line of lines) {
    if (/^\s*(```|~~~)/.test(line)) { fence = !fence; flush(); inBlock = false; continue; }
    if (fence) continue;
    const h = line.match(/^#{1,6}\s+(.*)$/);
    if (h) { flush(); inBlock = false; if (!title) title = plain(h[1]).replace(/\s*#+\s*$/, ''); continue; }
    if (!line.trim()) { flush(); inBlock = false; continue; }
    if (/^\s*(>\s*)?(\||[-*+]\s|\d+[.)]\s)/.test(line)) { flush(); inBlock = true; continue; }
    if (/^\s*(<!--|---\s*$|={3,})/.test(line)) { flush(); continue; }
    if (inBlock) continue;
    const isQuote = /^\s*>/.test(line);
    if (current.length && isQuote !== quote) flush();
    quote = isQuote;
    current.push(line.replace(/^\s*>\s?/, ''));
  }
  flush();
  const fallbackTitle = path.basename(rel, '.md').replace(/[-_]+/g, ' ').replace(/^./, (c) => c.toUpperCase());
  const len = (p) => plain(p.text).length;
  const status = (p) => /^(status|note|generated|created|updated)\b/i.test(plain(p.text));
  const para = (paras[0] && !status(paras[0]) && len(paras[0]) >= 30 ? paras[0] : null)
    ?? paras.find((p) => !p.quote && !status(p) && len(p) >= 40)
    ?? paras.find((p) => len(p) >= 30);
  return { title: title || fallbackTitle, description: para ? firstSentence(para.text) : null };
}

/** A spec's requirements, design and tasks say what they are for, from the spec's title. */
function specDescription(type, title) {
  if (type === 'Phase Summary') return `The summary of ${String(title).replace(/\s*:\s*summary\s*$/i, '').trim()}: what was built, its test script and what is open.`;
  if (!['Requirements', 'Design', 'Task List'].includes(type)) return null;
  const stem = String(title).replace(/\s*:\s*(requirements|design|tasks)\s*$/i, '').trim();
  return `The ${type === 'Task List' ? 'task list' : type.toLowerCase()} for ${stem}.`;
}

/** The tags of a document: its project and its folder within the bundle (and a spec's or phase's folder name). */
export function tagsFor(rel) {
  const p = segments(rel);
  const project = p[0].replace(/^nooblyjs-apps-(?=ai-)/, 'nooblyjs-');
  const tags = [project.startsWith('nooblyjs-ai-') ? project : 'nooblyjs-ai'];
  const i = p.findIndex((s) => BUNDLE_DIRS.includes(s));
  if (i >= 0 && p.length > i + 2) tags.push(p[i + 1].replace(/^\./, ''));
  if (i >= 0 && p.length > i + 3) tags.push(p[i + 2]);
  return [...new Set(tags.map((t) => t.toLowerCase()))];
}

const dumpKey = (key, value) => yaml.dump({ [key]: value }, { lineWidth: -1, flowLevel: 1 }).trimEnd();

/** The document with OKF frontmatter: missing keys added after the ones there; null when nothing is missing. */
export function conform(text, rel) {
  const { raw, data, body } = splitDoc(text);
  if (raw !== null && data === null) throw new Error(`${rel}: its frontmatter is not valid YAML`);
  const have = data ?? {};
  const { title, description: found } = summarise(body, rel);
  const type = have.type ?? typeFor(rel);
  const description = specDescription(type, have.title ?? title) ?? found;
  const add = [];
  if (!have.type) add.push(['type', type]);
  if (!have.title && !have.name) add.push(['title', title]);
  if (!have.description && description) add.push(['description', description]);
  if (!have.tags) add.push(['tags', tagsFor(rel)]);
  if (!add.length) return null;
  const lines = add.map(([k, v]) => dumpKey(k, v)).join('\n');
  const head = raw === null ? lines : `${raw.replace(/\s+$/, '')}\n${lines}`;
  const rest = raw === null ? body.replace(/^\r?\n/, '') : body;
  return `---\n${head}\n---\n${raw === null ? '\n' : ''}${rest}`;
}

async function* walk(dir) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true }).catch(() => [])) {
    if (SKIP.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (entry.name.endsWith('.md')) yield full;
  }
}

/** Every bundle (its folder) and every document, as paths relative to the solution root. */
export async function documents({ root = ROOT } = {}) {
  const apps = (await fs.readdir(path.join(root, APPS), { withFileTypes: true }).catch(() => [])).filter((d) => d.isDirectory()).map((d) => d.name);
  const projects = apps.map((name) => [APPS, name].join('/'));
  const bundles = [];
  const docs = [];
  const rel = (f) => path.relative(root, f).split(path.sep).join('/');
  for (const base of ['', ...projects]) {
    for (const b of BUNDLE_DIRS) {
      const dir = path.join(root, base, b);
      if (!(await fs.stat(dir).catch(() => null))?.isDirectory()) continue;
      const files = [];
      for await (const f of walk(dir)) if (!RESERVED.has(path.basename(f))) files.push(rel(f));
      if (!files.length) continue;
      bundles.push({ dir: rel(dir), project: base ? `nooblyjs-ai-${path.basename(base)}` : 'nooblyjs-ai', files: files.sort() });
      docs.push(...files);
    }
    if (!base) continue;
    for (const name of ROOT_DOCS) {
      if (await fs.stat(path.join(root, base, name)).catch(() => null)) docs.push(`${base}/${name}`);
    }
  }
  for (const ext of EXTERNAL) {
    for (const b of BUNDLE_DIRS) {
      const dir = path.join(root, ext.dir, b);
      if (!(await fs.stat(dir).catch(() => null))?.isDirectory()) continue;
      const files = [];
      for await (const f of walk(dir)) if (!RESERVED.has(path.basename(f))) files.push(rel(f));
      if (!files.length) continue;
      bundles.push({ dir: rel(dir), project: ext.project, files: files.sort() });
      docs.push(...files);
    }
  }
  for (const name of ROOT_DOCS) if (await fs.stat(path.join(root, name)).catch(() => null)) docs.push(name);
  return { bundles, docs };
}

/** The bundle-root index.md (OKF §8): okf_version, then one section per folder with each document and its description. */
export async function indexFor(bundle, { root = ROOT } = {}) {
  const groups = new Map();
  for (const f of bundle.files) {
    const inside = f.slice(bundle.dir.length + 1);
    const group = inside.includes('/') ? inside.split('/')[0] : '';
    if (!groups.has(group)) groups.set(group, []);
    const { data, body } = splitDoc(await fs.readFile(path.join(root, f), 'utf8'));
    const s = summarise(body, f);
    const title = String(data?.title ?? data?.name ?? s.title).replace(/[[\]]/g, '');
    const description = String(data?.description ?? specDescription(data?.type ?? typeFor(f), title) ?? s.description ?? '').replace(/\s+/g, ' ').trim();
    groups.get(group).push(`* [${title}](${inside.split('/').map(encodeURIComponent).join('/')})${description ? ` - ${description}` : ''}`);
  }
  const heading = (g) => (g ? g.replace(/^\./, '').replace(/[-_]+/g, ' ').replace(/^./, (c) => c.toUpperCase()) : 'Top level');
  const ordered = [...groups.keys()].sort((a, b) => (a === '' ? -1 : b === '' ? 1 : a.localeCompare(b)));
  const sections = ordered.map((g) => `## ${heading(g)}\n\n${groups.get(g).join('\n')}`);
  return `---\nokf_version: "${OKF_VERSION}"\n---\n\n# ${bundle.project}: ${bundle.dir.split('/').at(-1)}\n\n${GENERATED_NOTE}\n\n${sections.join('\n\n')}\n`;
}

/** What is out of OKF: documents with missing frontmatter or type, and stale indexes. */
export async function check({ root = ROOT } = {}) {
  const { bundles, docs } = await documents({ root });
  const copies = new Set((await steeringCopies({ root })).map((c) => path.relative(root, c.target).split(path.sep).join('/')));
  const problems = [];
  for (const f of docs) {
    const { raw, data } = splitDoc(await fs.readFile(path.join(root, f), 'utf8'));
    if (raw === null) problems.push(`${f}: no frontmatter`);
    else if (data === null) problems.push(`${f}: frontmatter is not valid YAML`);
    else if (!String(data.type ?? '').trim()) problems.push(`${f}: no type`);
    else if (!copies.has(f) && conform(await fs.readFile(path.join(root, f), 'utf8'), f)) problems.push(`${f}: missing title, description or tags`);
  }
  for (const b of bundles) {
    const want = await indexFor(b, { root });
    const now = await fs.readFile(path.join(root, b.dir, 'index.md'), 'utf8').catch(() => null);
    if (now !== want) problems.push(`${b.dir}/index.md: ${now === null ? 'missing' : 'out of date'}`);
  }
  return { problems, documents: docs.length, bundles: bundles.length };
}

async function main() {
  const root = ROOT;
  if (process.argv.includes('--check')) {
    const { problems, documents: n, bundles } = await check({ root });
    for (const p of problems) console.error(`not OKF: ${p}`);
    if (!problems.length) console.log(`okf: ${n} documents in ${bundles} bundles follow OKF v${OKF_VERSION}`);
    else console.error(`okf: ${problems.length} problem(s); run npm run docs:okf`);
    process.exitCode = problems.length ? 1 : 0;
    return;
  }
  const { bundles, docs } = await documents({ root });
  const copies = new Set((await steeringCopies({ root })).map((c) => path.relative(root, c.target).split(path.sep).join('/')));
  let changed = 0;
  for (const f of docs) {
    if (copies.has(f)) continue;
    const full = path.join(root, f);
    const next = conform(await fs.readFile(full, 'utf8'), f);
    if (next) { await fs.writeFile(full, next); changed += 1; }
  }
  for (const b of bundles) {
    const target = path.join(root, b.dir, 'index.md');
    const want = await indexFor(b, { root });
    if ((await fs.readFile(target, 'utf8').catch(() => null)) !== want) await fs.writeFile(target, want);
  }
  console.log(`okf: ${changed} documents given frontmatter, ${bundles.length} bundle indexes written; now run npm run steering:sync`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
